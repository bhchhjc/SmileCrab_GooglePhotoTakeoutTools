# ────────── 3D K-D Tree 공간 인덱스 구현 ──────────

class _KDNode:
    __slots__ = ("point", "data", "axis", "left", "right")

    def __init__(
        self,
        point: Tuple[float, float, float],
        data: Tuple[float, float, str, str, str],
        axis: int,
    ):
        self.point = point
        self.data = data    # (lat, lon, city_name, cc, admin1_name)
        self.axis = axis
        self.left: Optional[_KDNode] = None
        self.right: Optional[_KDNode] = None


def _lat_lon_to_cartesian(lat_deg: float, lon_deg: float) -> Tuple[float, float, float]:
    lat = math.radians(lat_deg)
    lon = math.radians(lon_deg)
    return (math.cos(lat) * math.cos(lon), math.cos(lat) * math.sin(lon), math.sin(lat))


def _build_kd_tree(points: List[Tuple[Tuple[float, float, float], Tuple[float, float, str, str, str]]], depth: int = 0) -> Optional[_KDNode]:
    if not points:
        return None
    axis = depth % 3
    points.sort(key=lambda p: p[0][axis])
    mid = len(points) // 2

    node = _KDNode(points[mid][0], points[mid][1], axis)
    node.left = _build_kd_tree(points[:mid], depth + 1)
    node.right = _build_kd_tree(points[mid + 1:], depth + 1)
    return node


def _nearest_neighbor(
    node: Optional[_KDNode],
    target: Tuple[float, float, float],
    best_dist: float,
    best_data: Optional[Tuple[float, float, str, str, str]],
) -> Tuple[float, Optional[Tuple[float, float, str, str, str]]]:
    if node is None:
        return best_dist, best_data

    dx = target[0] - node.point[0]
    dy = target[1] - node.point[1]
    dz = target[2] - node.point[2]
    d2 = dx * dx + dy * dy + dz * dz

    if d2 < best_dist:
        best_dist = d2
        best_data = node.data

    axis = node.axis
    axis_diff = target[axis] - node.point[axis]
    first_branch = node.left if axis_diff < 0 else node.right
    second_branch = node.right if axis_diff < 0 else node.left

    best_dist, best_data = _nearest_neighbor(first_branch, target, best_dist, best_data)

    if axis_diff * axis_diff < best_dist:
        best_dist, best_data = _nearest_neighbor(second_branch, target, best_dist, best_data)

    return best_dist, best_data


# ────────── GeoResolver 싱글톤 인스턴스 ──────────

class GeoResolver:
    """
    하이브리드 17만 거점 3단계 역지오코더
    - 레이어 1: 대표 명소 및 시·군·구 최우선 탐색
    - 레이어 2: 172,038개 전 세계 도시/마을 초고밀도 안전망
    """
    _instance: Optional[GeoResolver] = None

    def __new__(cls) -> GeoResolver:
        if cls._instance is None:
            cls._instance = super().__new__(cls)
            cls._instance._init_trees()
        return cls._instance

    def _init_trees(self):
        """K-D Tree 인덱스 사전 빌드"""
        # 1. 1차 최우선 거점 K-D Tree 빌드
        primary_points = []
        for city_info in _PRIMARY_CITIES:
            lat, lon = city_info[0], city_info[1]
            xyz = _lat_lon_to_cartesian(lat, lon)
            primary_points.append((xyz, city_info))
        self._primary_root = _build_kd_tree(primary_points)

        # 2. 2차 글로벌 17만 거점 K-D Tree 빌드 (바이너리 캐시)
        self._global_root: Optional[_KDNode] = None
        bin_path = Path(__file__).resolve().parent.parent.parent / "assets" / "geodata" / "cities150k.bin"
        if bin_path.exists():
            try:
                global_points = []
                with open(bin_path, "rb") as f:
                    buf = f.read()
                offset = 0
                buf_len = len(buf)
                while offset < buf_len:
                    lat, lon, b_cc, len_name, len_admin = struct.unpack_from("<ff2sBB", buf, offset)
                    offset += 12
                    name = buf[offset:offset+len_name].decode("utf-8")
                    offset += len_name
                    admin1 = buf[offset:offset+len_admin].decode("utf-8")
                    offset += len_admin
                    cc = b_cc.decode("ascii").strip()
                    xyz = _lat_lon_to_cartesian(lat, lon)
                    global_points.append((xyz, (lat, lon, name, cc, admin1)))
                self._global_root = _build_kd_tree(global_points)
            except Exception as e:
                logger.warning("[GeoResolver] 글로벌 바이너리 로드 실패: %s", e)

    @staticmethod
    def is_korean_system() -> bool:
        try:
            loc = locale.getdefaultlocale()[0] or ""
            if "ko" in loc.lower():
                return True
        except Exception:
            pass
        return "ko" in os.environ.get("LANG", "").lower()

    def resolve(
        self,
        lat: Optional[float],
        lon: Optional[float],
        language: GeoLanguage = GeoLanguage.KOREAN,
    ) -> LocationInfo:
        effective_lang = language
        if effective_lang == GeoLanguage.SYSTEM:
            effective_lang = GeoLanguage.KOREAN if self.is_korean_system() else GeoLanguage.ENGLISH

        # GPS 유효성 검사 (None 또는 0, 0)
        if lat is None or lon is None or (abs(lat) < 0.0001 and abs(lon) < 0.0001):
            if effective_lang == GeoLanguage.KOREAN:
                return LocationInfo("", "위치정보없음", "", "")
            else:
                return LocationInfo("", "Unknown_Location", "", "")

        target_xyz = _lat_lon_to_cartesian(lat, lon)

        # ── 하이브리드 탐색 ──
        # 1. 1차 최우선 거점에서 최근접 탐색
        p_dist, p_data = _nearest_neighbor(self._primary_root, target_xyz, float("inf"), None)

        # 유클리드 거리 d^2 < 0.000075 은 대략 지상 반경 약 30km에 해당
        chosen_data = None
        if p_data and p_dist < 0.000075:
            chosen_data = p_data
        elif self._global_root:
            # 2. 30km 반경에 1차 거점이 없는 경우 17만 글로벌 K-D Tree 탐색
            _g_dist, g_data = _nearest_neighbor(self._global_root, target_xyz, float("inf"), None)
            chosen_data = g_data or p_data
        else:
            chosen_data = p_data

        if not chosen_data:
            if effective_lang == GeoLanguage.KOREAN:
                return LocationInfo("", "위치정보없음", "", "")
            else:
                return LocationInfo("", "Unknown_Location", "", "")

        _c_lat, _c_lon, city_en, cc, admin1_en = chosen_data

        # ── 국가명 다국어 변환 ──
        country_info = COUNTRY_MAP.get(cc, (cc, cc))
        country_ko, country_en = country_info
        country_name = country_ko if effective_lang == GeoLanguage.KOREAN else country_en

        # ── 2단계: 주/도(Admin1) 다국어 변환 ──
        if effective_lang == GeoLanguage.KOREAN:
            state_name = ADMIN1_MAP_KO.get(admin1_en, admin1_en)
        else:
            state_name = admin1_en

        # ── 3단계: 도시명 다국어 및 스마트 동어반복 방어 ──
        if effective_lang == GeoLanguage.KOREAN:
            raw_city_ko = CITY_MAP_KO.get(city_en, city_en)
            city_name = ROLLUP_MAP_KO.get(raw_city_ko, raw_city_ko)
            if "_" in city_name:
                city_name = city_name.split("_")[-1]
        else:
            city_name = ROLLUP_MAP_EN.get(city_en, city_en)

        # ── 스마트 동어반복 방어 (Self-Tautology Suppression) ──
        # state_name과 city_name이 동일하여 발생하는 '인천광역시 > 인천', '빈 > 빈', '자그레브 > 자그레브'
        # 등의 동어반복을 감지하여 도심/중심부로 명확하게 지능형 분리
        if state_name and city_name:
            s_clean = state_name.replace("광역시", "").replace("특별시", "").replace("특별자치시", "").replace("특별자치도", "").replace("도", "").replace("주", "").replace("부", "").replace("현", "").strip()
            c_clean = city_name.replace("시", "").replace("군", "").replace("구", "").strip()
            if s_clean and c_clean and (s_clean == c_clean):
                if effective_lang == GeoLanguage.KOREAN:
                    city_name = f"{c_clean}도심"
                else:
                    city_name = f"{city_name} Central"

        return LocationInfo(cc, country_name, state_name, city_name)


# 편리한 전역 함수
def resolve_location(
    lat: Optional[float],
    lon: Optional[float],
    language: GeoLanguage = GeoLanguage.KOREAN,
) -> LocationInfo:
    """(위도, 경도) -> LocationInfo(country_code, country_name, state_name, city_name)"""
    return GeoResolver().resolve(lat, lon, language)
