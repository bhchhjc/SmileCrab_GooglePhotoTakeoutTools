class LocationInfo:
    """역지오코딩 3단계 계층 결과 객체"""
    __slots__ = ("country_code", "country_name", "state_name", "city_name")

    def __init__(self, country_code: str, country_name: str, state_name: str, city_name: str):
        self.country_code = country_code
        self.country_name = country_name
        self.state_name = state_name
        self.city_name = city_name

    def __iter__(self):
        """기존 3개 변수 언패킹 호환: cc, country_name, city_name = resolve(...)"""
        return iter((self.country_code, self.country_name, self.city_name))

    def __getitem__(self, index: int) -> str:
        fields = (self.country_code, self.country_name, self.city_name, self.state_name)
        return fields[index]

    def to_tuple_4(self) -> Tuple[str, str, str, str]:
        """4개 계층 전체 튜플: (국가코드, 국가명, 주/도명, 시/군/구명)"""
        return (self.country_code, self.country_name, self.state_name, self.city_name)

    def __repr__(self) -> str:
        return f"LocationInfo(country={self.country_name}({self.country_code}), state={self.state_name}, city={self.city_name})"


